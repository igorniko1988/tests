"""Задача 1. Исправь ловушку с аргументом по умолчанию.

Сейчас функция копит значения между вызовами. Перепиши её так, чтобы:
    f(1) -> [1]
    f(2) -> [2]
    f(3, []) -> [3]
    f(4) -> [4]

Проверка: pytest -k task_01 -q
"""


def f(n, acc = None):
    if acc is None:
        acc = []
    acc.append(n)
    return acc
