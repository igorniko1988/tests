"""Урок 3. `is` и `==`.

    python lessons/lesson_03_is_vs_eq.py
"""

a = [1, 2]
b = [1, 2]
c = a

print(a == b)    # True   значения одинаковые
print(a is b)    # False  это два разных списка
print(a is c)    # True   это один и тот же список

# `==` спрашивает: "содержимое одинаковое?"
# `is` спрашивает: "это один и тот же объект в памяти?"

# Где `is` нужен: сравнение с None
value = None
print(value is None)      # правильно
print(value == None)      # работает, но так не пишут

# Ловушка: маленькие числа и некоторые строки кешируются.
# Не используй `is` для сравнения чисел и строк, результат нестабилен.
x = 256
y = 256
print(x is y)             # True, но полагаться на это нельзя
