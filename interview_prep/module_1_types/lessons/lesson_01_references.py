# --- Изменяемый объект: список -------------------------------------------
a = [1, 2]
b = a              # второй ярлык на ТОТ ЖЕ список, не копия
b.append(3)
print("a =", a)                  # [1, 2, 3]
print("a is b:", a is b)         # True, это один объект

# --- Неизменяемый объект: число ------------------------------------------
x = 5
y = x
y += 1             # создаётся новое число 6, ярлык y переклеивается
print("x =", x, "y =", y)        # 5 6

# --- Неизменяемый объект: строка -----------------------------------------
s = "abc"
t = s
t += "d"           # новая строка "abcd", s остаётся "abc"
print("s =", s, "t =", t)

# --- Настоящая копия -----------------------------------------------------
c = a.copy()       # или list(a), или a[:]
c.append(99)
print("a =", a, "c =", c)        # a не изменился

# --- Функция меняет переданный список ------------------------------------
def add_item(lst):
    lst.append("new")

items = ["old"]
add_item(items)
print("items =", items)          # ['old', 'new']

# --- Ловушка: [[0]*3]*3 ---------------------------------------------------
bad = [[0] * 3] * 3              # три ярлыка на один список
bad[0][0] = 1
print("bad  =", bad)             # меняются все строки

good = [[0] * 3 for _ in range(3)]
good[0][0] = 1
print("good =", good)            # меняется только первая
