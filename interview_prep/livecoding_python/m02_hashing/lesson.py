part("2. set: только уникальные, быстрый in")
nums = [3, 1, 3, 2, 1]
s = set(nums)
print("ЧТО ВЫВЕДЕТ? set(nums) =", s, "len =", len(s))
# {1, 2, 3}, len 3 — дубли исчезли. Порядок в set НЕ гарантирован.

seen = set()
