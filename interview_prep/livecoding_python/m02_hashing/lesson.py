part("4. Подсчёт: три способа (спрашивают все три)")
word = "banana"

# 4.1 Руками через get — понимать обязательно
counts = {}
for ch in word:
    counts[ch] = counts.get(ch, 0) + 1
print("get:        ", counts)

# 4.2 defaultdict(int): у отсутствующего ключа значение сразу 0
dd = defaultdict(int)
for ch in word:
    dd[ch] += 1
print("defaultdict:", dict(dd))

# 4.3 Counter — то же одной строкой
c = Counter(word)
print("Counter:    ", c)
print("ЧТО ВЫВЕДЕТ? c['a'] =", c["a"], "| c['z'] =", c["z"])
# 3 и 0 — Counter не падает на отсутствующем ключе.
print("most_common(2) =", c.most_common(2))
print("Counter('ab') == Counter('ba') ->", Counter("ab") == Counter("ba"))   # так проверяют анаграммы

# ---------------------------------------------------------------------------
part("5. defaultdict(list): группировка")
words = ["apple", "avocado", "banana", "blueberry", "cherry"]
by_letter = defaultdict(list)
for w in words:
    by_letter[w[0]].append(w)      # нет ключа — создастся пустой список
print("ЧТО ВЫВЕДЕТ?", dict(by_letter))
# В автотестах так группируют, например, ответы API по статусу.

# ---------------------------------------------------------------------------
part("6. Что может быть ключом")
# Ключ должен быть hashable — неизменяемым: int, str, tuple, frozenset.
# list и dict ключом быть НЕ могут: их можно изменить, и hash «поплывёт».
d = {}
d[(1, 2)] = "tuple ok"
print(d)
try:
    d[[1, 2]] = "list?"
except TypeError as e:
    print("ЧТО ВЫВЕДЕТ? ->", e)
# unhashable type: 'list'. Поэтому в group anagrams ключ —
# "".join(sorted(word)) или tuple(sorted(word)), а не sorted(word).

# ---------------------------------------------------------------------------
part("7. Паттерн «уже видел» (seen)")
# Идём по списку один раз. Для каждого элемента спрашиваем:
# «я такой уже видел?» Ответ — за O(1), потому что прошлое лежит в set.
def first_repeat(items):
    seen = set()
    for x in items:
        if x in seen:
            return x
        seen.add(x)
    return None

print("ЧТО ВЫВЕДЕТ?", first_repeat([5, 3, 8, 3, 5]))
# 3: на 3 (индекс 3) мы уже видели 3. Пятёрка повторится позже.

# ---------------------------------------------------------------------------
part("8. Паттерн «ищу пару» (complement) — основа Two Sum")
# Задача: есть ли два числа с суммой target?
# В лоб: каждую пару, O(n^2).
# Через dict: для текущего x нужна пара need = target - x.
#   Сначала СПРАШИВАЕМ «need уже был?», потом ЗАПИСЫВАЕМ x.
#   В dict храним число -> индекс, чтобы вернуть индексы.
def has_pair(nums, target):
    seen = {}
    for i, x in enumerate(nums):
        need = target - x
        if need in seen:
            return (seen[need], i)
        seen[x] = i
    return None

print("ЧТО ВЫВЕДЕТ?", has_pair([2, 7, 11, 15], 9))
print("ЧТО ВЫВЕДЕТ?", has_pair([3, 3], 6))
# (0, 1) в обоих. Во втором случае важен порядок «спросить, потом записать»:
# если сначала записать 3, то на индексе 0 найдём саму себя -> (0, 0), ошибка.

# ---------------------------------------------------------------------------
part("9. Сложность — что говорить на собесе")
# dict/set: in, get, set, del — O(1) в среднем (в худшем O(n) при коллизиях,
#   но так говорить не нужно, только если спросят «а в худшем?»).
# Память: O(n) — это цена скорости. «Обменял память на время».
# Counter(s) — O(n). most_common(k) — O(n log k). sorted — O(n log n).
#
# Шпаргалка «какой инструмент»:
#   есть ли повтор / видел ли раньше      -> set
#   нужен индекс или значение по ключу    -> dict
#   посчитать сколько раз                 -> Counter
#   сгруппировать по признаку             -> defaultdict(list)
#   сравнить «одинаковый состав»          -> Counter(a) == Counter(b)
