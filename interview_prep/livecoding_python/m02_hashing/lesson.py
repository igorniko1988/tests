def part(title):
    print(f"\n=== {title} ===")


# ---------------------------------------------------------------------------
part("1. Зачем: поиск в list против поиска в set")
# x in list — Python проверяет элементы по одному: O(n).
# x in set  — Python считает hash(x) и сразу идёт в нужную «ячейку»: O(1).
#
# Аналогия: list — стопка бумаг, ищешь листая. dict — шкаф с подписанными
# ящиками: знаешь имя — открываешь нужный ящик сразу.

print("hash('eat') =", hash("eat"))   # число, по нему выбирается ячейка
print("hash(42)    =", hash(42))

